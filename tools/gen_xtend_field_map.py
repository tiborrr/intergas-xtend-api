#!/usr/bin/env python3
"""Parse known_xtend_codes.md and emit firmware/BoilerBridge_Server/xtend_field_map.gen.h."""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MD = ROOT / "known_xtend_codes.md"
OUT = ROOT / "firmware" / "BoilerBridge_Server" / "xtend_field_map.gen.h"

KEY_RE = re.compile(r"^[0-9a-fA-F]{1,4}$")


def c_escape(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", " ")
        .replace("\r", "")
    )


def parse_factor(s: str) -> float:
    s = s.strip()
    if not s:
        return 1.0
    try:
        return float(s)
    except ValueError:
        return 1.0


def main() -> None:
    rows: list[tuple[str, int, str, str, str, float]] = []
    for line in MD.read_text(encoding="utf-8").splitlines():
        line = line.rstrip()
        if "|" not in line or line.startswith("#"):
            continue
        if line.startswith("name|") or line.startswith("------"):
            continue
        parts = line.split("|")
        if len(parts) < 6:
            continue
        name, key, typ, unit, fac_s = parts[0], parts[1], parts[2], parts[3], parts[4]
        value_col = "|".join(parts[5:])
        key = key.strip()
        if not KEY_RE.match(key):
            continue
        key_int = int(key, 16)
        if key_int > 0xFFFF:
            continue
        factor = parse_factor(fac_s)
        rows.append(
            (
                c_escape(name.strip()),
                key_int,
                c_escape(typ.strip()),
                c_escape(unit.strip()),
                c_escape(value_col.strip()),
                factor,
            )
        )

    lines_out = [
        "/* Generated by tools/gen_xtend_field_map.py — do not edit. */",
        "#ifndef XTEND_FIELD_MAP_GEN_H",
        "#define XTEND_FIELD_MAP_GEN_H",
        "",
        "#include <Arduino.h>",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "struct XtendField {",
        "  uint16_t key;",
        "  const char *name;",
        "  const char *type;",
        "  const char *unit;",
        "  float factor;",
        "};",
        "",
        "static const XtendField kXtendFields[] = {",
    ]
    for name, key_int, typ, unit, _val, factor in rows:
        lines_out.append(
            f'  {{ 0x{key_int:04x}, "{name}", "{typ}", "{unit}", {factor}f }},'
        )
    lines_out.extend(
        [
            "};",
            "",
            "static const size_t kXtendFieldCount = sizeof(kXtendFields) / sizeof(kXtendFields[0]);",
            "",
            "inline const XtendField *xtendFieldFind(uint16_t key) {",
            "  for (size_t i = 0; i < kXtendFieldCount; ++i) {",
            "    if (kXtendFields[i].key == key) {",
            "      return &kXtendFields[i];",
            "    }",
            "  }",
            "  return nullptr;",
            "}",
            "",
            "#endif",
            "",
        ]
    )
    OUT.write_text("\n".join(lines_out), encoding="utf-8")
    print(f"Wrote {len(rows)} fields to {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
